/** สุ่มเคล็ดลับ โดยไม่ให้ซ้ำกับข้อเดิม (ถ้ามี) */
export function randomTipIndex(exclude?: number, rng: () => number = Math.random): number {
  if (KID_TIPS.length <= 1) return 0
  let i = Math.floor(rng() * (KID_TIPS.length - (exclude === undefined ? 0 : 1)))
  if (exclude !== undefined && i >= exclude) i++
  return i
}
